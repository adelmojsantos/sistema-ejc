CREATE TABLE public.email_institucional_conversas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  assunto text NOT NULL DEFAULT '(sem assunto)',
  contato_email text NOT NULL,
  contato_nome text,
  status text NOT NULL DEFAULT 'novo'
    CHECK (status IN ('novo', 'em_atendimento', 'resolvido')),
  responsavel_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  ultima_mensagem_em timestamptz NOT NULL DEFAULT now(),
  criada_em timestamptz NOT NULL DEFAULT now(),
  atualizada_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.email_institucional_mensagens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  conversa_id uuid NOT NULL REFERENCES public.email_institucional_conversas(id) ON DELETE CASCADE,
  direcao text NOT NULL CHECK (direcao IN ('entrada', 'saida')),
  provider_message_id text,
  in_reply_to text,
  references_header text,
  remetente_email text NOT NULL,
  remetente_nome text,
  destinatarios text[] NOT NULL DEFAULT '{}',
  copias text[] NOT NULL DEFAULT '{}',
  assunto text NOT NULL DEFAULT '(sem assunto)',
  previa text NOT NULL DEFAULT '',
  r2_texto_key text,
  r2_html_key text,
  r2_raw_key text,
  tamanho_bytes bigint NOT NULL DEFAULT 0 CHECK (tamanho_bytes >= 0),
  status_envio text CHECK (status_envio IS NULL OR status_envio IN ('enviando', 'enviado', 'falhou')),
  erro_envio text,
  criado_por uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  recebida_em timestamptz,
  enviada_em timestamptz,
  criada_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT email_institucional_mensagens_provider_unique UNIQUE (provider_message_id)
);

CREATE TABLE public.email_institucional_anexos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  mensagem_id uuid NOT NULL REFERENCES public.email_institucional_mensagens(id) ON DELETE CASCADE,
  nome text NOT NULL,
  mime_type text NOT NULL DEFAULT 'application/octet-stream',
  tamanho_bytes bigint NOT NULL CHECK (tamanho_bytes >= 0),
  content_id text,
  r2_key text NOT NULL UNIQUE,
  criada_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.email_institucional_leituras (
  conversa_id uuid NOT NULL REFERENCES public.email_institucional_conversas(id) ON DELETE CASCADE,
  usuario_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  lida_ate timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conversa_id, usuario_id)
);

CREATE TABLE public.email_institucional_eventos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversa_id uuid NOT NULL REFERENCES public.email_institucional_conversas(id) ON DELETE CASCADE,
  mensagem_id uuid REFERENCES public.email_institucional_mensagens(id) ON DELETE SET NULL,
  usuario_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  tipo text NOT NULL CHECK (tipo IN ('recebida', 'lida', 'status_alterado', 'responsavel_alterado', 'resposta_enviada', 'resposta_falhou', 'anexo_baixado', 'excluida')),
  detalhes jsonb NOT NULL DEFAULT '{}'::jsonb,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX email_institucional_conversas_ultima_idx
