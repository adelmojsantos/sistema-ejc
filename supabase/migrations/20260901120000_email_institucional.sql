CREATE OR REPLACE FUNCTION public.marcar_email_institucional_como_lido(
  p_conversa_id uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.pode_visualizar_email_institucional(auth.uid()) THEN
    RAISE EXCEPTION 'Acesso não autorizado.' USING ERRCODE = '42501';
  END IF;

  INSERT INTO public.email_institucional_leituras (conversa_id, usuario_id, lida_ate)
  VALUES (p_conversa_id, auth.uid(), now())
